float MC_Math_Sin(float angle)
{
    float x = angle * (float)MC_MATH_TABLE_SIZE * (1.0f / MC_MATH_2PI);   /* 归一化到 [0, N) */
    int32_t n = (int32_t)x;                 /* 向零截断 */
    float frac = x - (float)n;              /* 小数部分 */
    uint32_t i;

    if (frac < 0.0f) {                      /* 负数角度修正：floor 语义 */
        n -= 1;
        frac += 1.0f;
    }
    i = (uint32_t)n & MC_MATH_TABLE_MASK;   /* 取模（N 为 2 的幂，位与） */

    /* 线性插值 */
    return mc_sin_table[i] + (mc_sin_table[(i + 1u) & MC_MATH_TABLE_MASK] - mc_sin_table[i]) * frac;
}

float MC_Math_Cos(float angle)
{
    return MC_Math_Sin(angle + MC_MATH_HALF_PI);
}

/**
 * @brief  一次算出 sin/cos（省掉 cos 那次角度归一化与索引计算）
 * @note   实现与 MC_Math_Sin 相同，只是：
 *         - 角度归一化只做一次；
 *         - cos 直接用"同一 frac、索引 +N/4"取表（cos θ = sin(θ+π/2)），
 *           不再算 (angle+π/2) 再跑一遍完整查表。
 *         数值与 Sin/Cos 分别调用一致（差值为 float 舍入量级）。
 */
void MC_Math_SinCos(float angle, float *s, float *c)
{
    float x = angle * (float)MC_MATH_TABLE_SIZE * (1.0f / MC_MATH_2PI);
    int32_t n = (int32_t)x;
    float frac = x - (float)n;
    uint32_t i, j;
    float s0, s1, c0, c1;

    if (frac < 0.0f) {                      /* 负数角度修正：floor 语义 */
        n -= 1;
        frac += 1.0f;
    }
    i = (uint32_t)n & MC_MATH_TABLE_MASK;
    j = (i + (MC_MATH_TABLE_SIZE / 4u)) & MC_MATH_TABLE_MASK;   /* +90° = 表索引 +N/4 */

    s0 = mc_sin_table[i];
    s1 = mc_sin_table[(i + 1u) & MC_MATH_TABLE_MASK];
    c0 = mc_sin_table[j];
    c1 = mc_sin_table[(j + 1u) & MC_MATH_TABLE_MASK];

    *s = s0 + (s1 - s0) * frac;
    *c = c0 + (c1 - c0) * frac;
}
